function caminhoAsset(nomeFicheiro) {
  return ASSETS_JOGO.caminho(nomeFicheiro);
}

function normalizarCaminhoAsset(caminho) {
  if (!caminho || typeof caminho !== "string") return "";
  if (caminho.startsWith("data:") || caminho.startsWith("http://") || caminho.startsWith("https://")) return caminho;
  const nomeFicheiro = caminho.split("?")[0].split("#")[0].split("/").pop();
  return caminhoAsset(nomeFicheiro);
}

